/** Static payload served when every model in the chain fails. */
export function slidesFallback(body: any) {
  const conceptName = body?.concept?.name || 'شرح المفهوم الذكي';
  const principles = body?.concept?.keyPrinciples || [
    'فهم الأركان والمبادئ الأساسية للمفهوم',
    'ربط النظرية بالتطبيق العملي في أمثلة واقعية',
    'تحديد الثغرات والأخطاء الشائعة وتصحيحها',
  ];

  return {
    presentationTitle: `عرض تقديمي تفاعلي: ${conceptName}`,
    slides: [
      {
        slideNumber: 1,
        title: `المقدمة والمستهدف: ${conceptName}`,
        bulletPoints: [
          `المفهوم الأساسي: ${body?.concept?.summary || 'استيعاب الأفكار الجوهرية وصياغتها بأسلوبك الشخصي.'}`,
          'الهدف التشخيصي: قياس فجوة الثقة بين المعرفة الفعلية واليقين المعلن.',
          'طريقة البطة: الشرح المباشر البسيط لاكتشاف المفاهيم المغلوطة تلقائياً.',
        ],
        duckTip: 'كواك! الشرح البسيط الجلي هو أول أركان الفهم الراسخ!',
      },
      {
        slideNumber: 2,
        title: 'المبادئ والقوانين الجوهرية',
        bulletPoints: principles.map((p: string, idx: number) => `المبدأ ${idx + 1}: ${p}`),
        duckTip: 'البطة تنصحك: حافظ على تطبيق المبادئ بالتسلسل دون قفز على المراحل.',
      },
      {
        slideNumber: 3,
        title: 'التطبيق العملي والتحديات الواقعية',
        bulletPoints: [
          'تحليل الشروط والمعطيات قبل البدء بالتنفيذ.',
          'التحقق من صحة النتائج ومقارنتها بالقواعد العلمية المقررة.',
          'تجنب الأخطاء الشائعة والافتراضات غير المثبتة.',
        ],
        duckTip: 'التطبيق في مواقف جديدة هو المقياس الحقيقي لعمق الاستيعاب.',
      },
      {
        slideNumber: 4,
        title: 'الخلاصة وأفضل الممارسات',
        bulletPoints: [
          'المراجعة الدورية لنقاط الضعف والتأكد من ردم فجوة اليقين.',
          'شرح المفاهيم لشخص آخر أو للبطة لاختبار ثبات المعلومة.',
          'ربط كل فكرة بسياقها الأكبر في المقرر الدراسي.',
        ],
        duckTip: 'كواك! المعلم الحقيقي هو من يستطيع تبسيط أعقد المفاهيم بوضوح تام!',
      },
    ],
  };
}
